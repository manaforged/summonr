use super::*;

const MOCKUP: [&str; 19] = [
    "          ┌──────────────────────────┐",
    "        ┌──────────────────────────┐ │",
    "      ┌──────────────────────────┐ │ │",
    "    ┌──────────────────────────┐ │ │─┘",
    "  ┌──────────────────────────┐ │ │─┘",
    "┏━━━━━━━━━━━━━━━━━━━━━━━━━━┓ │ │─┘───┐",
    "┃                          ┃ │─┘───┐ │",
    "┃                          ┃─┘───┐ │ │",
    "┃    ┏━━━━━━━━━━━━━━━━━━━━━┛───┐ │ │ │",
    "┃    ┃ └─────────────────────┐ │ │ │ │",
    "┃    ┗━━━━━━━━━━━━━━━━━━━━━┓ │ │ │ │ │",
    "┃                          ┃ │ │ │ │ │",
    "┃                          ┃ │ │ │ │ │",
    "┗━━━━━━━━━━━━━━━━━━━━━┓    ┃ │ │ │ │─┘",
    "  ┌───────────────────┃    ┃ │ │ │─┘",
    "┏━━━━━━━━━━━━━━━━━━━━━┛    ┃ │ │─┘",
    "┃                          ┃ │─┘",
    "┃                          ┃─┘",
    "┗━━━━━━━━━━━━━━━━━━━━━━━━━━┛",
];

#[test]
fn the_line_stack_matches_the_terminal_s_mockup() {
    let drawn: Vec<String> = draw(Mark::Lines, u64::MAX / 2)
        .iter()
        .map(|row| {
            row.iter()
                .map(|glyph| glyph.map_or(' ', |glyph| glyph.text))
                .collect::<String>()
                .trim_end()
                .to_string()
        })
        .collect();
    assert_eq!(drawn, MOCKUP);
}
